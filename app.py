@st.cache_resource
def get_preprocessor():
    # Explicitly use Porter stemming across entire pipeline
    return TextPreprocessor(use_stemming=True)


@st.cache_resource
def load_models_cached():
    """
    Loads trained TF-IDF vectorizer and ML models.
    Returns (None, None) if artifacts do not exist.
    """
    try:
        if os.path.exists("models/tfidf_vectorizer.joblib"):
            vectorizer, models = ModelTrainer.load_artifacts("models")
            return vectorizer, models
        return None, None
    except Exception as e:
        st.error(f"Error loading model files: {e}")
        return None, None


def load_saved_metrics():
    """
    Loads metrics.json generated by train.py.
    Returns None if missing.
    """
    metrics_path = "models/metrics.json"
    if os.path.exists(metrics_path):
        try:
            with open(metrics_path, "r") as f:
                return json.load(f)
        except Exception:
            return None
    return None


